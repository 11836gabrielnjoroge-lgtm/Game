function cloneMoves(overrides: Partial<Record<MoveId, Partial<MoveDefinition>>>): Record<MoveId, MoveDefinition> {
  const result = {} as Record<MoveId, MoveDefinition>;
  for (const key of Object.keys(BASE_MOVES) as MoveId[]) {
    result[key] = {
      ...BASE_MOVES[key],
      ...(overrides[key] ?? {}),
      hitbox: {
        ...BASE_MOVES[key].hitbox,
        ...(overrides[key]?.hitbox ?? {}),
      },
    };
  }
  return result;
}

